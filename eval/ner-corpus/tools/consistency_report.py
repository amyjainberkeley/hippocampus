#!/usr/bin/env python3
"""Reproducible annotation-consistency report for the synthetic NER corpus.

A synthetic corpus generated by an LLM fleet (24 generators + 24 auditors)
has residual annotation drift, exactly as a human-multi-annotator corpus
has measurable inter-annotator disagreement. Rather than hide it, this
script MEASURES it so the README can report it honestly and so reviewers
can re-derive the numbers. It emits, per the frozen corpus:

  1. ambiguous-surface multi-kind table — surfaces labeled as >1 kind.
     For MCI this is mostly INTENTIONAL: the corpus deliberately reuses
     ambiguous tokens (Phoenix, Washington, Madison, Apple, ...) in
     different senses. High-frequency multi-kind = designed ambiguity;
     a single-off minority kind = either genuine contextual ambiguity or
     residual noise.
  2. speaker-tag consistency — chat/email "Name:" line-initial tags that
     are vs are not labeled person_name, when the name is labeled
     person_name elsewhere.
  3. article-inclusion / boundary variation — known entity surfaces that
     appear unlabeled as a substring (usually because the labeled span
     omits a leading determiner like "the"; the RELAXED scorer mode
     absorbs these, EXACT penalizes them).

Usage:  python3 consistency_report.py --corpus synthetic/corpus.full.json [--json-out ...]
"""

from __future__ import annotations

import argparse
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

TAG_RE = re.compile(r"(?m)^\s*([A-Z][a-zA-Z]+):")


def labeled_spans(rec):
    return [(e["span_start"], e["span_end"]) for e in rec["entities"]]


def in_any_span(bs, be, spans):
    return any(s <= bs and be <= e for s, e in spans)


def byte_off(text, char_idx):
    return len(text[:char_idx].encode("utf-8"))


def report(recs):
    labeled_kinds = defaultdict(Counter)
    surfaces = set()
    n_mentions = 0
    for r in recs:
        for e in r["entities"]:
            labeled_kinds[e["mention_text"]][e["kind"]] += 1
            surfaces.add(e["mention_text"])
            n_mentions += 1

    multi_kind = {s: dict(k) for s, k in labeled_kinds.items() if len(k) > 1}

    person_surfaces = {s for s, k in labeled_kinds.items() if "person_name" in k}
    sp_labeled, sp_unlabeled = Counter(), Counter()
    for r in recs:
        t, spans = r["text"], labeled_spans(r)
        for m in TAG_RE.finditer(t):
            name = m.group(1)
            bs, be = byte_off(t, m.start(1)), byte_off(t, m.end(1))
            if in_any_span(bs, be, spans):
                sp_labeled[name] += 1
            elif name in person_surfaces:
                sp_unlabeled[name] += 1

    multiword = [s for s in surfaces if len(s.split()) >= 2 and re.search(r"[A-Za-z]", s)]
    boundary = Counter()
    for r in recs:
        t, spans = r["text"], labeled_spans(r)
        for s in multiword:
            idx = t.find(s)
            if idx < 0:
                continue
            bs = byte_off(t, idx)
            be = bs + len(s.encode("utf-8"))
            if not in_any_span(bs, be, spans):
                boundary[s] += 1

    genuine_speaker_miss = sum(sp_unlabeled.values())
    summary = {
        "samples": len(recs),
        "mentions": n_mentions,
        "multi_kind_surfaces": len(multi_kind),
        "speaker_tags_labeled": sum(sp_labeled.values()),
        "speaker_tags_unlabeled_but_known_person": genuine_speaker_miss,
        "boundary_variation_occurrences": sum(boundary.values()),
        "approx_one_directional_noise_pct": round(100 * (genuine_speaker_miss) / max(1, n_mentions), 2),
    }
    return summary, multi_kind, sp_labeled, sp_unlabeled, boundary


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--corpus", required=True, type=Path)
    ap.add_argument("--json-out", type=Path, default=None)
    args = ap.parse_args()
    recs = json.loads(args.corpus.read_text(encoding="utf-8"))
    summary, multi_kind, sp_labeled, sp_unlabeled, boundary = report(recs)

    print("=== annotation-consistency summary ===")
    print(json.dumps(summary, indent=2))
    print("\n=== ambiguous surfaces labeled as >1 kind (intentional design) ===")
    for s, k in sorted(multi_kind.items(), key=lambda x: -sum(x[1].values())):
        print(f"  {s!r:28} {k}")
    print(f"\n=== speaker-tag 'Name:' UNLABELED but name is a known person elsewhere ({sum(sp_unlabeled.values())}) ===")
    for n, c in sp_unlabeled.most_common():
        print(f"  {n!r}: {c}x")
    print(f"\n=== boundary/article variation (top 15 of {len(boundary)}) ===")
    for s, c in boundary.most_common(15):
        print(f"  {s!r}: {c}x unlabeled-substring")

    if args.json_out:
        args.json_out.write_text(json.dumps({
            "summary": summary,
            "multi_kind_surfaces": multi_kind,
            "speaker_tags_unlabeled": dict(sp_unlabeled),
            "boundary_variation": dict(boundary),
        }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
