var gate = RecallPresentationGate()
precondition(!gate.request(initialLaunch: true, state: .idle))
precondition(!gate.consumeIfReady(state: .starting))
precondition(!gate.consumeIfReady(state: .crashed(reason: "key unavailable")))
precondition(!gate.request(initialLaunch: false, state: .starting))
precondition(gate.consumeIfReady(state: .running))
precondition(!gate.consumeIfReady(state: .running))
precondition(!gate.request(initialLaunch: true, state: .running))
precondition(gate.request(initialLaunch: false, state: .running))
precondition(gate.request(initialLaunch: false, state: .paused))
precondition(!gate.consumeIfReady(state: .paused))
precondition(gate.request(initialLaunch: false, state: .stopped))
precondition(!gate.request(initialLaunch: false, state: .crashed(reason: "x")))
precondition(gate.consumeIfBlocked(state: .crashed(reason: "x")))
precondition(!gate.consumeIfReady(state: .running))
// With memory to read, the window opens at once in any state.
precondition(gate.request(initialLaunch: false, state: .starting, memoryReady: true))
precondition(gate.request(initialLaunch: false, state: .crashed(reason: "x"), memoryReady: true))
precondition(!gate.consumeIfBlocked(state: .crashed(reason: "x"), memoryReady: true))
print("Recall readiness, once-only launch, stopped, failed start, reopen and memory-ready checks passed")
